const dicts: Record<Locale, Record<Key, string>> = { en, ru };

export function translate(locale: Locale, key: Key, vars?: Record<string, string | number>) {
  let s = dicts[locale]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function guessLocale(): Locale {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem("hjem-locale");
    if (saved === "en" || saved === "ru") return saved;
  } catch {}
  return navigator.language?.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function rememberLocale(locale: Locale) {
  try {
    localStorage.setItem("hjem-locale", locale);
  } catch {}
}
